        LDI     R0, #0           ; PC=0x020: аккумулятор = 0
        LDI     R1, #10          ; PC=0x021: счётчик итераций = 10
        LDI     R2, #0x0025      ; PC=0x022: адрес начала тела цикла (loop_body)
        MOV     LOOP_TGT, R2     ; PC=0x023: задаём адрес возврата цикла
        MOV     LOOP_CNT, R1     ; PC=0x024: задаём счётчик итераций (10)

loop_body:
        L ADD   R0, #1           ; PC=0x025: тело цикла с L-префиксом (бит конца цикла)

        HALT                     ; PC=0x026: после цикла в R0 должно быть 0x000A (10)
