        ; === Основная программа (внешний цикл: 3 итерации) ===
        LDI     R0, #0           ; PC=0x020: общий счётчик (ожидаем 3 * 4 = 12 = 0x000C)
        LDI     R1, #3           ; PC=0x021: 3 итерации внешнего цикла
        LDI     R2, #0x0025      ; PC=0x022: адрес начала outer_loop (PC=0x025)
        MOV     LOOP_TGT, R2     ; PC=0x023
        MOV     LOOP_CNT, R1     ; PC=0x024

outer_loop:
      L CALL    inner_func       ; PC=0x025: тело внешнего цикла из 1 инструкции с префиксом L!
                                 ; (вызывает функцию и по возврате делает итерацию внешнего цикла)

        HALT                     ; PC=0x026: стоп, R0 должен быть равен 0x000C (12)

        ; === Подпрограмма со своим аппаратным циклом (4 итерации) ===
inner_func:
        ; 1. Сохраняем контекст внешнего цикла (и адрес возврата SHADOW на всякий случай)
        MOV     R10, LOOP_CNT    ; PC=0x027: сохраняем счётчик внешнего цикла
        MOV     R11, LOOP_TGT    ; PC=0x028: сохраняем адрес возврата внешнего цикла
        MOV     R12, SHADOW      ; PC=0x029: сохраняем адрес возврата из CALL

        ; 2. Настраиваем и запускаем внутренний цикл (4 итерации)
        LDI     R3, #4           ; PC=0x02A: 4 итерации внутреннего цикла
        LDI     R4, #0x002E      ; PC=0x02B: адрес начала inner_loop (PC=0x02E)
        MOV     LOOP_TGT, R4     ; PC=0x02C
        MOV     LOOP_CNT, R3     ; PC=0x02D

inner_loop:
      L ADD     R0, #1           ; PC=0x02E: тело внутреннего цикла (с префиксом L)

        ; 3. Восстанавливаем контекст внешнего цикла и возвращаемся
        MOV     SHADOW, R12      ; PC=0x02F: восстанавливаем адрес возврата
        MOV     LOOP_TGT, R11    ; PC=0x030: восстанавливаем цель внешнего цикла
        MOV     LOOP_CNT, R10    ; PC=0x031: восстанавливаем остаток счётчика внешнего цикла
        RET                      ; PC=0x032: возврат во внешний цикл
